// Command rbacgen 从 go-zero 的 .api 文件生成一个"路由 @doc 元数据"文件。
//
//	go run . -api ../../app/admin/doc/admin.api -out <输出目录> -pkg docmeta
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/zeromicro/go-zero/tools/goctl/api/parser"
	"github.com/zeromicro/go-zero/tools/goctl/api/spec"
)

func main() {
	apiFile := flag.String("api", "", "根 .api 文件路径")
	outDir := flag.String("out", "", "生成文件的输出目录")
	pkgName := flag.String("pkg", "docmeta", "生成文件的 package 名")
	outName := flag.String("name", "docmeta_gen.go", "生成文件名")
	flag.Parse()

	if *apiFile == "" || *outDir == "" {
		fmt.Fprintln(os.Stderr, "用法: rbacgen -api <根 .api 文件> -out <输出目录> [-pkg docmeta] [-name docmeta_gen.go]")
		os.Exit(2)
	}

	api, err := parser.Parse(*apiFile)
	if err != nil {
		fatal(fmt.Errorf("解析 .api 失败: %w", err))
	}

	meta, err := extract(api)
	if err != nil {
		fatal(err)
	}

	src, err := format.Source([]byte(render(*pkgName, meta)))
	if err != nil {
		fatal(fmt.Errorf("gofmt 失败: %w", err))
	}

	outFile := filepath.Join(*outDir, *outName)
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		fatal(fmt.Errorf("写文件失败: %w", err))
	}
	fmt.Printf("✅ 生成 %s,共 %d 条路由 @doc 元数据\n", outFile, len(meta))
}

// extract 收集每条路由 @doc 的全部 key-value,key 为 "METHOD /path"。
func extract(api *spec.ApiSpec) (map[string]map[string]string, error) {
	meta := make(map[string]map[string]string)

	for _, g := range api.Service.Groups {
		prefix := strings.TrimRight(g.GetAnnotation(spec.RoutePrefixKey), "/")

		for _, r := range g.Routes {
			kv := make(map[string]string)
			for k, v := range r.AtDoc.Properties {
				if v = unquote(v); v != "" {
					kv[k] = v
				}
			}
			if len(kv) == 0 {
				continue // 没有 @doc key-value 的路由不登记
			}

			path := prefix + r.Path
			if strings.Contains(path, ":") {
				fmt.Fprintf(os.Stderr, "⚠ 路由含路径参数,运行时按 r.URL.Path 精确匹配将失效: %s %s\n",
					strings.ToUpper(r.Method), path)
			}

			key := strings.ToUpper(r.Method) + " " + path
			if _, dup := meta[key]; dup {
				return nil, fmt.Errorf("重复路由 key,同 method+path 声明了多次: %s", key)
			}
			meta[key] = kv
		}
	}

	return meta, nil
}

// render 把元数据渲染成稳定(排序)的 Go 源码,含 ctx 注入中间件与读取器。
func render(pkg string, meta map[string]map[string]string) string {
	keys := make([]string, 0, len(meta))
	for k := range meta {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by rbacgen. DO NOT EDIT.\n")
	b.WriteString("// 事实源为各 .api 路由的 @doc(...);改动请改 .api 后重新生成。\n\n")
	b.WriteString("package " + pkg + "\n\n")
	b.WriteString("import (\n\t\"context\"\n\t\"net/http\"\n\t\"strings\"\n)\n\n")
	b.WriteString("// docMeta 每条路由 @doc 里声明的全部 key-value,key 为 \"METHOD /path\"。\n")
	b.WriteString("var docMeta = map[string]map[string]string{\n")
	for _, k := range keys {
		b.WriteString(fmt.Sprintf("\t%q: {%s},\n", k, renderKV(meta[k])))
	}
	b.WriteString("}\n\n")
	b.WriteString(`type ctxKey struct{}

// Inject 是 go-zero 中间件:把当前路由 @doc 的全部 key-value 注入请求 ctx。
// 用法示例:server.Use(` + pkg + `.Inject),或按分组挂在 rest.WithMiddleware 上。
func Inject(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if m, ok := docMeta[strings.ToUpper(r.Method)+" "+r.URL.Path]; ok {
			r = r.WithContext(context.WithValue(r.Context(), ctxKey{}, m))
		}
		next(w, r)
	}
}

// FromContext 取当前路由 @doc 的全部 key-value(未命中返回 nil)。
func FromContext(ctx context.Context) map[string]string {
	m, _ := ctx.Value(ctxKey{}).(map[string]string)
	return m
}

// Value 取当前路由 @doc 中某个 key 的值。
func Value(ctx context.Context, key string) (string, bool) {
	m, _ := ctx.Value(ctxKey{}).(map[string]string)
	v, ok := m[key]
	return v, ok
}
`)
	return b.String()
}

func renderKV(kv map[string]string) string {
	inner := make([]string, 0, len(kv))
	for k := range kv {
		inner = append(inner, k)
	}
	sort.Strings(inner)
	parts := make([]string, 0, len(inner))
	for _, k := range inner {
		parts = append(parts, fmt.Sprintf("%q: %q", k, kv[k]))
	}
	return strings.Join(parts, ", ")
}

// unquote 去掉外层引号与空白。
func unquote(s string) string {
	return strings.TrimSpace(strings.Trim(strings.TrimSpace(s), `"`))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "✗ "+err.Error())
	os.Exit(1)
}
